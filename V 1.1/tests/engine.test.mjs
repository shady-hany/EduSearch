import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {search,phraseMatches,queries} from '../src/engine.mjs';
const load=p=>JSON.parse(readFileSync(new URL(p,import.meta.url),'utf8'));
const model=load('../data/model.json');
const reference=load('../outputs/query_results.json');
const expected=[[['d1',1],['d5',.4476],['d2',.4226],['d9',.1939]],[['d3',.4226],['d5',.3051],['d8',.2731]],[['d5',.5322]],[['d1',1],['d2',.4226],['d9',.1939]]];
queries.forEach((q,i)=>test(q,()=>{const result=search(model,q);assert.deepEqual(result.results.map(r=>[r.id,Number(r.score.toFixed(4))]),expected[i]);result.results.forEach((r,j)=>{const x=reference[i].results[j];assert.deepEqual(r.positions,x.positions);assert.ok(Math.abs(r.score-x.score)<1e-12)});assert.ok(Math.abs(result.queryLength-reference[i].queryLength)<1e-12)}));
test('exact phrase positions and repeated phrases',()=>{assert.deepEqual(phraseMatches(model.index,'online learning'),{d1:[1],d2:[1],d5:[1,8],d9:[1]});assert.deepEqual(phraseMatches(model.index,'student assessment'),{d3:[1],d5:[3],d8:[1,3]})});
test('arbitrary phrases, case, whitespace and unknown tokens',()=>{assert.equal(search(model,'  ONLINE   LEARNING ').results.length,4);assert.equal(search(model,'classroom teaching').results.length,2);assert.equal(search(model,'learning online').results.length,0);assert.equal(search(model,'constructor').results.length,0);assert.equal(search(model,'no results').results.length,0)});
test('invalid or unsupported syntax',()=>{for(const q of ['','online learning AND','online learning OR','online learning NOT','AND online learning'])assert.throws(()=>search(model,q))});
test('operator case sensitivity: uppercase operators vs normal words',()=>{
  const normalAnd = search(model, 'online learning and student assessment');
  assert.equal(normalAnd.mode, 'PHRASE');
  assert.deepEqual(normalAnd.phrases, ['online learning and student assessment']);
  const capsAnd = search(model, 'online learning AND student assessment');
  assert.equal(capsAnd.mode, 'AND');
  assert.deepEqual(capsAnd.phrases, ['online learning', 'student assessment']);
  const capsOr = search(model, 'online learning OR student assessment');
  assert.equal(capsOr.mode, 'OR');
  assert.deepEqual(capsOr.phrases, ['online learning', 'student assessment']);
  assert.equal(capsOr.results.length, 6);
  const capsXor = search(model, 'online learning XOR student assessment');
  assert.equal(capsXor.mode, 'XOR');
  assert.deepEqual(capsXor.results.map(r=>r.id), ['d1','d2','d3','d8','d9']);
  const capsXnor = search(model, 'online learning XNOR student assessment');
  assert.equal(capsXnor.mode, 'XNOR');
  assert.deepEqual(capsXnor.results.map(r=>r.id), ['d5','d10','d4','d7','d6']);
  const normalOr = search(model, 'online learning or student assessment');
  assert.equal(normalOr.mode, 'PHRASE');
  const capsNot = search(model, 'online learning NOT student assessment');
  assert.equal(capsNot.mode, 'NOT');
  assert.deepEqual(capsNot.results.map(r=>r.id), ['d1','d2','d9']);
  const normalNot = search(model, 'online learning not student assessment');
  assert.equal(normalNot.mode, 'PHRASE');
  const normalAndNot = search(model, 'online learning and not student assessment');
  assert.equal(normalAndNot.mode, 'PHRASE');
  const capsAndNot = search(model, 'online learning AND NOT student assessment');
  assert.equal(capsAndNot.mode, 'NOT');
  assert.deepEqual(capsAndNot.results.map(r=>r.id), ['d1','d2','d9']);
  const phraseWithAnd = search(model, 'research and data');
  assert.equal(phraseWithAnd.mode, 'PHRASE');
  assert.equal(phraseWithAnd.results[0]?.id, 'd8');
  const mixed = search(model, 'research and data AND student assessment');
  assert.equal(mixed.mode, 'AND');
  assert.deepEqual(mixed.phrases, ['research and data', 'student assessment']);
  assert.equal(mixed.results[0]?.id, 'd8');
});
